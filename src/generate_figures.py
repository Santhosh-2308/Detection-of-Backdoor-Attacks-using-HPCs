"""
Generates figures/score_distribution.png and figures/sensitivity_curve.png
from the trained detector bundle and the perturbation sweep results.

Run AFTER train.py and perturbation_sweep.py (in that order) so this reads
current, consistent numbers rather than stale ones:

    python train.py --data ../data/trace.csv --out ../models/detector.joblib
    python perturbation_sweep.py
    python generate_figures.py

The other report figures (perturbation_shape_sweep.png, fpr_sensitivity_tradeoff.png,
baseline_comparison.png) are generated by their respective sweep scripts directly
(perturbation_sweep.py, hyperparam_sweep.py, baseline_comparison.py) since they're
one-off plots of each script's own output; this script covers the two figures that
read the final trained model itself.
"""
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import joblib
import numpy as np
import pandas as pd

from features import build_feature_matrix
from train import ensemble_score


def plot_score_distribution(bundle_path="../models/detector.joblib",
                             data_path="../data/trace.csv",
                             out_path="../figures/score_distribution.png"):
    bundle = joblib.load(bundle_path)
    df = pd.read_csv(data_path)
    feat = build_feature_matrix(df)[bundle["feature_names"]]
    X = bundle["scaler"].transform(feat.values)
    scores = ensemble_score(bundle["models"], bundle["ref_scores"], X)

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.hist(scores, bins=40, color="#4C72B0", edgecolor="white")
    ax.axvline(bundle["threshold"], color="crimson", linestyle="--",
               label=f"threshold={bundle['threshold']:.4f}")
    ax.set_xlabel("Ensemble anomaly score")
    ax.set_ylabel("Count (benign traces)")
    n_models = len(bundle["models"])
    ax.set_title(f"Benign training-score distribution ({n_models}-model ensemble, "
                 f"{bundle.get('feature_set', 'raw')} features)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    print(f"saved {out_path}")


def plot_sensitivity_curve(sweep_csv="../figures/perturbation_sweep_results.csv",
                            out_path="../figures/sensitivity_curve.png"):
    df = pd.read_csv(sweep_csv)
    d = dict(zip(df["perturbation"], df["flag_rate_pct"]))
    pcts = [0, 2, 5, 10, 20]
    keys = ["uniform_scale_2pct", "uniform_scale_5pct", "uniform_scale_10pct", "uniform_scale_20pct"]
    missing = [k for k in keys if k not in d]
    if missing:
        raise ValueError(
            f"perturbation_sweep_results.csv is missing {missing} -- "
            f"run perturbation_sweep.py first (uses matching perturbation names)."
        )
    flagged = [1.0] + [d[k] for k in keys]  # 0% baseline assumed ~= calibrated target FPR

    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(pcts, flagged, marker="o", color="#DD8452")
    ax.set_xlabel("Synthetic perturbation magnitude (%)")
    ax.set_ylabel("Flagged as anomalous (%)")
    ax.set_title("Detector sensitivity to synthetic counter perturbation\n"
                 "(sanity check only, not real backdoor data)")
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    print(f"saved {out_path}  (values used: {dict(zip(pcts, flagged))})")


if __name__ == "__main__":
    plot_score_distribution()
    plot_sensitivity_curve()
